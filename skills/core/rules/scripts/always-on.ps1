param(
    [switch]$Apply,
    [ValidateSet('global', 'project')][string]$Scope = 'global',
    [ValidateSet('all', 'core')][string]$Set,
    [string]$ProjectPath = (Get-Location).ProviderPath,
    [string]$Path,
    [string]$CorePath = (Join-Path $PSScriptRoot '../references/core.md'),
    [string]$ExtraPath
)

# Keeps a generated copy of the rules in an always-on instructions file: the user's global file by
# default, or a project's .github/copilot-instructions.md. The set is all (core and extra rules) or
# core; it is recorded in the block, and a later run without -Set keeps it. Without -Apply it only
# reports Missing, Unmanaged, InSync, or Drifted. Text outside the generated block, including the
# Personal or Project rules sections, is never changed.
$ErrorActionPreference = 'Stop'
$begin = '<!-- rules:core:begin -->'
$end = '<!-- rules:core:end -->'
$utf8 = [Text.UTF8Encoding]::new($false)
if (-not $Path) { $Path = if ($Scope -eq 'project') { Join-Path $ProjectPath '.github/copilot-instructions.md' } else { Join-Path $HOME '.copilot/copilot-instructions.md' } }
# The extra rules sit beside the core rules; a missing file means there are none.
if (-not $ExtraPath) { $ExtraPath = Join-Path (Split-Path -Parent $CorePath) 'extra.md' }

function Get-CoreRuleLines {
    param([string]$SourcePath)
    $lines = [IO.File]::ReadAllLines((Resolve-Path -LiteralPath $SourcePath).ProviderPath)
    $start = [Array]::FindIndex($lines, [Predicate[string]] { param($line) $line -match '^1\. ' })
    if ($start -lt 0) { throw "No numbered rules found in $SourcePath." }
    $rules = New-Object 'System.Collections.Generic.List[string]'
    for ($i = $start; $i -lt $lines.Count; $i++) {
        $line = $lines[$i]
        $next = if ($i + 1 -lt $lines.Count) { $lines[$i + 1] } else { '' }
        if ($line -match '^\d+\. ' -or $line -match '^\s+\S' -or ($line -eq '' -and $next -match '^\d+\. ')) { $rules.Add($line) }
        else { break }
    }
    return $rules
}

function Get-ExtraRuleLines {
    param([string]$SourcePath)
    if (-not (Test-Path -LiteralPath $SourcePath -PathType Leaf)) { return @() }
    $lines = [IO.File]::ReadAllLines((Resolve-Path -LiteralPath $SourcePath).ProviderPath)
    $start = [Array]::FindIndex($lines, [Predicate[string]] { param($line) $line -match '^- ' })
    if ($start -lt 0) { return @() }
    $rules = New-Object 'System.Collections.Generic.List[string]'
    for ($i = $start; $i -lt $lines.Count; $i++) {
        $line = $lines[$i]
        $next = if ($i + 1 -lt $lines.Count) { $lines[$i + 1] } else { '' }
        if ($line -match '^- ' -or $line -match '^\s+\S' -or ($line -eq '' -and $next -match '^- ')) { $rules.Add($line) }
        else { break }
    }
    return $rules
}

function Get-DetailLink {
    param([string]$SourcePath, [string]$TargetPath)
    $folder = Split-Path -Parent (Resolve-Path -LiteralPath $SourcePath).ProviderPath
    if ($Scope -eq 'project') {
        # Project files are usually shared, so they link the public reference, never a local path.
        $manifest = Join-Path (Split-Path -Parent $folder) 'skill.json'
        if (-not (Test-Path -LiteralPath $manifest -PathType Leaf)) { return '' }
        $skill = [IO.File]::ReadAllText($manifest) | ConvertFrom-Json
        if (-not $skill.homepage -or -not $skill.source.path) { return '' }
        return "$(([string]$skill.homepage).TrimEnd('/'))/blob/main/$($skill.source.path)/references/ai-principles.md"
    }
    [IO.Path]::GetRelativePath((Split-Path -Parent ([IO.Path]::GetFullPath($TargetPath))), (Join-Path $folder 'ai-principles.md')).Replace('\', '/')
}

function New-CoreBlock {
    param([string]$SourcePath, [string]$ExtraSource, [string]$TargetPath, [string]$Eol, [string]$RuleSet)
    $sources = if ($RuleSet -eq 'core') { 'references/core.md' } else { 'references/core.md and references/extra.md' }
    $block = @(
        $begin,
        "<!-- Generated by /rules (set: $RuleSet) from the rules skill's $sources. Do not edit here; /rules apply rewrites this block. -->",
        '# Core working rules',
        '',
        'Apply these rules to all coding work.',
        ''
    ) + @(Get-CoreRuleLines $SourcePath)
    $link = Get-DetailLink -SourcePath $SourcePath -TargetPath $TargetPath
    if ($link) { $block += @('', "For clarification, read the [detailed reference]($link).") }
    $extra = if ($RuleSet -eq 'core') { @() } else { @(Get-ExtraRuleLines $ExtraSource) }
    if ($extra.Count) { $block += @('', '# Extra rules', '') + $extra }
    $block += $end
    return ($block -join $Eol)
}

$section = if ($Scope -eq 'project') {
    @('# Project rules', '', '<!-- /rules <rule> project adds this project''s own rules here. -->')
}
else {
    @('# Personal rules', '', '<!-- Private: /rules <rule> adds rules here by default. They stay on this machine and never go to SkillVault. -->')
}

$exists = Test-Path -LiteralPath $Path -PathType Leaf
$text = if ($exists) { [IO.File]::ReadAllText($Path) } else { '' }
$eol = if ($text.Contains("`r`n")) { "`r`n" } else { "`n" }
$beginCount = ([regex]::Matches($text, [regex]::Escape($begin))).Count
$endCount = ([regex]::Matches($text, [regex]::Escape($end))).Count
$wellFormed = $beginCount -eq 1 -and $endCount -eq 1 -and $text.IndexOf($begin) -lt $text.IndexOf($end)
# Keep the set the block already holds unless the caller chooses one; blocks without a record hold all.
$current = if ($wellFormed) { [regex]::Match($text.Substring($text.IndexOf($begin), $text.IndexOf($end) - $text.IndexOf($begin)), '\(set: (all|core)\)').Groups[1].Value } else { '' }
$ruleSet = if ($Set) { $Set } elseif ($current) { $current } else { 'all' }
$generated = New-CoreBlock -SourcePath $CorePath -ExtraSource $ExtraPath -TargetPath $Path -Eol $eol -RuleSet $ruleSet

if (-not $exists) { $status = 'Missing' }
elseif ($beginCount -eq 0 -and $endCount -eq 0) { $status = 'Unmanaged' }
elseif ($beginCount -ne 1 -or $endCount -ne 1 -or $text.IndexOf($begin) -gt $text.IndexOf($end)) {
    throw "The generated rules block in $Path is malformed: expect one '$begin' before one '$end'. Fix it by hand; nothing was changed."
}
else {
    $startIndex = $text.IndexOf($begin)
    $endIndex = $text.IndexOf($end) + $end.Length
    $status = if ($text.Substring($startIndex, $endIndex - $startIndex) -ceq $generated) { 'InSync' } else { 'Drifted' }
}

$applied = $false
if ($Apply -and $status -ne 'InSync') {
    $next = switch ($status) {
        'Missing' { (@($generated, '') + $section + @('')) -join $eol }
        # An existing project file already holds that project's instructions, so it gets no new heading.
        'Unmanaged' {
            if ($Scope -eq 'project') { (@($generated, '', $text.TrimEnd("`r", "`n"), '')) -join $eol }
            else { (@($generated, '') + $section + @('', $text.TrimEnd("`r", "`n"), '')) -join $eol }
        }
        'Drifted' { $text.Substring(0, $startIndex) + $generated + $text.Substring($endIndex) }
    }
    $folder = Split-Path -Parent ([IO.Path]::GetFullPath($Path))
    if (-not (Test-Path -LiteralPath $folder)) { New-Item -ItemType Directory -Path $folder -Force | Out-Null }
    [IO.File]::WriteAllText($Path, $next, $utf8)
    $applied = $true
}

[pscustomobject]@{ path = [IO.Path]::GetFullPath($Path); scope = $Scope; set = $ruleSet; status = $status; applied = $applied } | ConvertTo-Json
